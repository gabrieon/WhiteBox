// One-off build script for src/games/word-lock/words.js.
//
// Run: node scripts/build-word-list.mjs
//
// Not part of the app. Kept so the word list is reproducible and auditable
// rather than an opaque blob someone hand-edited at 2am.

import fs from 'node:fs';

const FREQ_URL = 'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt';
const DICT_URL = 'https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt';

async function fetchWords(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return (await res.text()).split(/\r?\n/).map((s) => s.trim());
}

const fiveLetters = (w) => w.length === 5 && /^[a-z]{5}$/.test(w);

const freq = (await fetchWords(FREQ_URL)).filter(fiveLetters);
const dictionary = (await fetchWords(DICT_URL)).filter(fiveLetters);
const dictionarySet = new Set(dictionary);

// Answers: common enough that a player could plausibly have guessed them, and
// free of proper nouns. This is the curated, careful list.
const answers = [...new Set(freq)].filter((w) => dictionarySet.has(w)).sort();

// Guesses: every five-letter word a Scrabble player would recognise. Deliberately
// far larger than the answer pool, because rejecting an obvious guess ("crane")
// is the single most complained-about flaw in this genre — the frequency list is
// not an admission test for what a player is allowed to type.
const guesses = [...new Set(dictionary)].sort();

const header = `// Word lists for WORDLOCK. Generated by scripts/build-word-list.mjs — do not edit by hand.
//
// Two separate lists, deliberately different sizes:
//
//   ANSWERS (${answers.length}) — the solution pool, curated from the intersection of
//   the Google 10000 English frequency list and the ENABLE1 Scrabble dictionary.
//   The frequency half keeps answers ordinary; the Scrabble half keeps people,
//   places, brands and abbreviations (aaron, india, nokia, xanax) out of the
//   pool, since none of those belong as the answer to a puzzle.
//
//   GUESSES (${guesses.length}) — every five-letter Scrabble word, accepted for any guess.
//   Keeping this much larger than ANSWERS is the point: a player who types a
//   real word should never be told it isn't in the game.
//
// Built this way because intersecting once for both lists was wrong — it dropped
// perfectly ordinary words like CRANE and ZEBRA that simply fell outside the
// top-10k frequency cut, which made the game feel broken.
`;

const fmt = (list) => list.map((w) => JSON.stringify(w)).join(',');

const out = `${header}
export const ANSWERS = [\n${fmt(answers)},\n];

export const GUESSES = new Set([\n${fmt(guesses)},\n]);
`;

fs.mkdirSync('src/games/word-lock', { recursive: true });
fs.writeFileSync('src/games/word-lock/words.js', out);

console.log(`answers: ${answers.length}   guesses: ${guesses.length}`);
for (const probe of ['crane', 'zebra', 'radio', 'tiger', 'north', 'juice']) {
  console.log(`  ${probe.padEnd(7)} answer=${answers.includes(probe)} guess=${guesses.includes(probe)}`);
}
