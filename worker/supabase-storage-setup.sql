-- Game thumbnail storage on Supabase Storage.
--
-- Run this once: Supabase Dashboard -> SQL Editor -> New query -> paste -> Run.
-- Idempotent — safe to run again.
--
-- Design: the bucket is PUBLIC for reads but WRITES require an authenticated
-- Supabase user. That lets the Worker upload using the player's own session
-- token, so no service-role secret ever exists in our infrastructure — there is
-- no privileged credential to leak or rotate.
--
-- Where authorisation actually happens
-- -----------------------------------
-- These policies are deliberately COARSE. They only require "signed in" and
-- "the object lives under games/". Real authorisation — "this player owns this
-- game" — is enforced in the Worker, which verifies the game row's creator_id
-- before it ever calls Supabase Storage. Two layers doing the same job is how
-- policies drift out of sync, so the policy stays dumb and the Worker stays
-- strict.

-- 1. The bucket.
--    public = true          -> anyone can read an object by URL. Cover art in a
--                              public grid is public data; this is what lets an
--                              <img> load it without a signed request.
--    file_size_limit        -> 1 MB backstop. The browser compresses to ~30-90 KB
--                              before upload, so anything larger is a client
--                              that skipped compression.
--    allowed_mime_types     -> matches what the Worker's magic-byte sniffer
--                              accepts. Belt and braces: the Worker already
--                              verifies the real type from the file header.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'game-thumbs',
  'game-thumbs',
  true,
  1048576,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update set
  public             = excluded.public,
  file_size_limit    = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- 2. Writes. One policy covering insert/update/delete keeps the rules simple and
--    means re-uploading a thumbnail needs no separate upsert grant. The path is
--    always games/<uuid>/thumb, generated by the Worker from a game id the
--    caller proved they own.
drop policy if exists "authenticated users write thumbnails" on storage.objects;
create policy "authenticated users write thumbnails"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'game-thumbs'
    and (storage.foldername(name))[1] = 'games'
  );

drop policy if exists "authenticated users replace thumbnails" on storage.objects;
create policy "authenticated users replace thumbnails"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'game-thumbs'
    and (storage.foldername(name))[1] = 'games'
  );

drop policy if exists "authenticated users remove thumbnails" on storage.objects;
create policy "authenticated users remove thumbnails"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'game-thumbs'
    and (storage.foldername(name))[1] = 'games'
  );